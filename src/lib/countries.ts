const regionNames = new Intl.DisplayNames(['en'], { type: 'region' })

const NAMES = new Map<string, string>()
for (const code of ISO_3166_ALPHA_2) {
  const name = regionNames.of(code)
  if (name && name !== code) NAMES.set(code, name)
}

export const EVENT_COUNTRIES = [...NAMES]
  .map(([value, title]) => ({ title, value }))
  .sort((a, b) => a.title.localeCompare(b.title, 'en'))

/** "GB" → "United Kingdom". Null for a code outside the list. */
export function countryName(code: string | null | undefined): string | null {
  return (code && NAMES.get(code)) || null
}
